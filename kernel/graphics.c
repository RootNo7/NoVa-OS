static const uint8_t *glyph(char c) {
    if (c >= 'A' && c <= 'Z') return font5x7[c-'A'];
    if (c >= '0' && c <= '9') return font5x7[26 + c-'0'];
    return 0;
}

void gfx_palette_init(void) {
    static const uint8_t colors[16][3] = {
        {0,0,0},{12,16,24},{12,24,50},{18,34,64},
        {10,42,30},{10,34,48},{38,36,16},{42,42,42},
        {18,18,18},{20,30,45},{24,48,90},{30,55,110},
        {18,80,58},{72,68,24},{46,46,50},{63,63,63}
    };
    outb(0x3C8, 0);
    for (int i=0;i<16;i++) {
        outb(0x3C9, colors[i][0]);
        outb(0x3C9, colors[i][1]);
        outb(0x3C9, colors[i][2]);
    }
}

void graphics_init(void) {
    gfx_palette_init();
    gfx_clear(1);
}

void gfx_clear(uint8_t c) {
    for (int y=0;y<VGA_HEIGHT;y++) for (int x=0;x<VGA_WIDTH;x++) fb[y*VGA_WIDTH+x] = c;
}

void gfx_rect(int x, int y, int w, int h, uint8_t c) {
    if (w <= 0 || h <= 0) return;
    int x0=x<0?0:x, y0=y<0?0:y, x1=x+w, y1=y+h;
    if (x1>VGA_WIDTH) x1=VGA_WIDTH;
    if (y1>VGA_HEIGHT) y1=VGA_HEIGHT;
    for (int yy=y0; yy<y1; ++yy) {
        volatile uint8_t *row = fb + yy*VGA_WIDTH;
        for (int xx=x0; xx<x1; ++xx) row[xx]=c;
    }
}

static char upper(char c) {
    if (c >= 'a' && c <= 'z') return (char)(c-'a'+'A');
    return c;
}

static void pixel(int x,int y,uint8_t c) {
    if ((unsigned)x < VGA_WIDTH && (unsigned)y < VGA_HEIGHT) fb[y*VGA_WIDTH+x]=c;
}

void gfx_text(int x, int y, uint8_t c, const char *s, size_t max_len) {
    for (size_t i=0; s[i] && i<max_len; ++i) {
        char ch = upper(s[i]);
        const uint8_t *g = glyph(ch);
        if (!g) {
            if (ch=='.') { pixel(x+2,y+6,c); pixel(x+3,y+6,c); }
            else if (ch==':') { pixel(x+2,y+2,c); pixel(x+2,y+6,c); }
            else if (ch=='-') for (int xx=1;xx<5;xx++) pixel(x+xx,y+4,c);
            else if (ch=='_') for (int xx=0;xx<5;xx++) pixel(x+xx,y+6,c);
            else if (ch=='/') { pixel(x+4,y,c); pixel(x+3,y+1,c); pixel(x+2,y+2,c); pixel(x+1,y+3,c); pixel(x,y+4,c); }
            else if (ch=='>') { pixel(x,y+2,c); pixel(x+1,y+3,c); pixel(x,y+4,c); }
            else if (ch=='>') {}
            else if (ch=='!') { for(int yy=0;yy<5;yy++) pixel(x+2,y+yy,c); pixel(x+2,y+6,c); }
            x += 6; continue;
        }
        for (int row=0; row<7; ++row) {
            uint8_t bits=g[row];
            for (int col=0; col<5; ++col) if (bits & (1u<<(4-col))) pixel(x+col,y+row,c);
        }
        x += 6;
    }
}
